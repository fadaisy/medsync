-- ── encounter_symptom_observations: ROS three-state status ───────────────────
-- 'present' | 'denies' (pertinent negative). 'not_asked' is NEVER persisted — it
-- is the absence of a row. NULL = an HPC capture row (not an ROS screen).
ALTER TABLE public.encounter_symptom_observations
  ADD COLUMN IF NOT EXISTS status text;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'enc_symptom_obs_status_check') THEN
    ALTER TABLE public.encounter_symptom_observations
      ADD CONSTRAINT enc_symptom_obs_status_check
      CHECK (status IS NULL OR status IN ('present', 'denies'));
  END IF;
END $$;

