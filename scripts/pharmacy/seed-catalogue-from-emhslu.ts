/**
 * Seed the shared medicines catalogue from an EMHSLU edition already loaded by load-national-list.ts
 * (catalogue slice Step 2; ADR 0456). Owner-run, after 0251 and 0252. It writes proposals only: each medicine
 * enters the catalogue when two curators confirm it (0251's two-person rule). Idempotent: a re-run proposes
 * nothing already proposed (S3). The report (every row as a medicine, merged, or refused with why; every
 * printed form and what it maps to) is written to docs/pharmacy/catalogue/seed-report.md.
 *
 *   npm run pharmacy:seed-catalogue -- data/pharmacy/national-list/emhslu-2023.csv --edition "EMHSLU 2023"
 *   ... --apply --actor <your auth user id>
 */
import { readFileSync, writeFileSync } from "node:fs";
import type { EmrDb, EmrTx } from "@/lib/emr/db";
import type { SeedReport } from "@/lib/pharmacy/shared-catalogue/seed";
import { eq } from "drizzle-orm";

import {
  pharmacyNationalListEditions,
  pharmacyNationalListRows,
} from "@/db/schema/pharmacy-dispensing";
import { readNationalList } from "@/lib/pharmacy/national-list";
import { seedFromEmhslu } from "@/lib/pharmacy/shared-catalogue/seed";
import { proposeSeed } from "@/lib/pharmacy/shared-catalogue/store";
import { asActor, DryRun, runCli } from "../emr/_cli";

export const REPORT = "docs/pharmacy/catalogue/seed-report.md";

export async function seedCatalogue(
  db: EmrDb,
  csv: string,
  editionName: string,
  apply: boolean,
  actor?: string,
): Promise<{ report: SeedReport; proposed: number; already: number; rows: number }> {
  const { rows, rejected } = readNationalList(csv);
  if (rejected.length)
    throw new Error(`The file has ${rejected.length} unreadable lines; fix it first.`);
  const report = seedFromEmhslu(rows);
  const [edition] = await db
    .select({ id: pharmacyNationalListEditions.id })
    .from(pharmacyNationalListEditions)
    .where(eq(pharmacyNationalListEditions.name, editionName));
  if (!edition)
    throw new Error(
      `No edition named "${editionName}" is loaded; run load-national-list.ts first.`,
    );
  const loaded = await db
    .select({ id: pharmacyNationalListRows.id, line: pharmacyNationalListRows.sourceLine })
    .from(pharmacyNationalListRows)
    .where(eq(pharmacyNationalListRows.editionId, edition.id));
  const rowIdForLine = new Map(loaded.filter((r) => r.line !== null).map((r) => [r.line!, r.id]));
  if (loaded.length !== rows.length)
    throw new Error(
      `The file has ${rows.length} rows; edition "${editionName}" has ${loaded.length}. Same file?`,
    );

  let counts = { proposed: 0, already: 0 };
  try {
    await db.transaction(async (t) => {
      const tx = t as unknown as EmrTx;
      await asActor(tx, actor);
      counts = await proposeSeed(tx, editionName, report.medicines, rowIdForLine);
      if (!apply) throw new DryRun();
    });
  } catch (e) {
    if (!(e instanceof DryRun)) throw e;
  }
  return { report, ...counts, rows: rows.length };
}

export function reportMarkdown(r: Awaited<ReturnType<typeof seedCatalogue>>, mode: string): string {
  const meds = r.report.medicines.filter((m) => m.kind === "medicine");
  const forms = new Map<string, { code: string | null; n: number }>();
  for (const m of meds) {
    const k = m.printedForm ?? "(none printed)";
    const f = forms.get(k) ?? { code: m.formCode, n: 0 };
    f.n += m.lines.length;
    forms.set(k, f);
  }
  const noted = r.report.medicines.filter((m) => m.notes.length);
  return [
    `# Catalogue seed from EMHSLU: report`,
    ``,
    `${mode}. Generated by \`scripts/pharmacy/seed-catalogue-from-emhslu.ts\`.`,
    ``,
    `| | Count |`,
    `|---|---|`,
    `| Rows in the edition | ${r.rows} |`,
    `| Medicines proposed from medicine rows | ${meds.length} |`,
    `| Health supplies proposed | ${r.report.medicines.length - meds.length} |`,
    `| Rows merged into an earlier identical row (same medicine, another section) | ${r.report.merged.length} |`,
    `| Rows refused, with the reason below | ${r.report.refused.length} |`,
    `| Multi-ingredient medicines | ${meds.filter((m) => m.ingredients.length > 1).length} |`,
    `| Medicines with no signed form (a curator sets it) | ${meds.filter((m) => !m.formCode).length} |`,
    `| Medicines with no route known | ${meds.filter((m) => !m.routes.length).length} |`,
    `| Flagged on the list (kept flagged) | ${r.report.medicines.filter((m) => m.flagged).length} |`,
    `| Proposals written this run | ${r.proposed} |`,
    `| Already proposed earlier | ${r.already} |`,
    ``,
    `Every row is accounted for: medicines' lines + refused = ${
      r.report.medicines.reduce((n, m) => n + m.lines.length, 0) + r.report.refused.length
    } of ${r.rows}.`,
    ``,
    `## Refused rows`,
    ``,
    ...(r.report.refused.length
      ? r.report.refused.map((x) => `- line ${x.line}: ${x.reason}`)
      : ["None."]),
    ``,
    `## Printed forms and the signed form each maps to`,
    ``,
    `| Printed form | Signed form | Rows |`,
    `|---|---|---|`,
    ...[...forms.entries()]
      .sort((a, b) => b[1].n - a[1].n)
      .map(([k, f]) => `| ${k.replace(/\|/g, "/")} | ${f.code ?? "not mapped"} | ${f.n} |`),
    ``,
    `## For a curator: medicines with notes`,
    ``,
    ...noted.map(
      (m) => `- **${m.displayName}** (line ${m.lines.join(", ")}): ${m.notes.join(" ")}`,
    ),
  ].join("\n");
}

if (process.argv[1]?.endsWith("seed-catalogue-from-emhslu.ts")) {
  const args = process.argv.slice(2);
  const file = args[0];
  const e = args.indexOf("--edition");
  const edition = e >= 0 ? args[e + 1] : undefined;
  void runCli(
    'Seed the catalogue from a loaded EMHSLU edition: <file.csv> --edition "<name>" [--apply --actor <uuid>].',
    async ({ db, apply, actor }) => {
      if (!file || file.startsWith("--") || !edition)
        throw new Error("Give the CSV file and --edition.");
      const r = await seedCatalogue(db, readFileSync(file, "utf8"), edition, apply, actor);
      writeFileSync(REPORT, reportMarkdown(r, apply ? "Applied" : "Dry run") + "\n");
      console.log(
        `${r.report.medicines.length} items; ${r.proposed} proposals ${apply ? "written" : "would be written"}.`,
      );
      console.log(`Report at ${REPORT}.`);
    },
  );
}
