/**
 * TM-9 (Lab test menu v2 Step 7; TM-D10): each hospital's per-LOINC lab offerings become per-test offerings.
 * The rule is `planOfferingMigration` (lib/lab/test-menu.ts); this script only feeds it and writes the report to
 * docs/lab/test-menu-v2/migration-report.md. A dry run is the default; `--apply --actor <uuid>` writes the test
 * rows (never overwriting one) in one transaction. The old rows are left in place, unread. Run after 0171 and 0172:
 *
 *   npm run lab:migrate-offerings              # dry run, report
 *   npm run lab:migrate-offerings -- --apply --actor <your auth user id>
 *   npm run lab:migrate-offerings -- --rows <capture.json>   # offline dry run from a captured row list
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { EmrDb } from "@/lib/emr/db";
import type { LegacyRow, MigrationPlan, SectionKey } from "@/lib/lab/test-menu";
import { and, eq, isNotNull, isNull } from "drizzle-orm";

import { diagnosticOfferings, hospitalDepartments, hospitals, testCatalogue } from "@/db/schema";
import { planOfferingMigration, SECTIONS } from "@/lib/lab/test-menu";
import { LAB_SECTIONS } from "@/supabase/functions/_shared/services-hub";
import { asActor, runCli } from "../emr/_cli";

type Json = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
const root = process.cwd();
const read = (rel: string): Json => JSON.parse(readFileSync(join(root, rel), "utf8"));
export const REPORT = "docs/lab/test-menu-v2/migration-report.md";

/** LOINC → concept ids, from the files the registry and 0158 were built from (the same everywhere). */
export function loincIndex(): Map<string, string[]> {
  const m = new Map<string, string[]>();
  const add = (code: string | null | undefined, id: string) => {
    if (code) m.set(code, [...new Set([...(m.get(code) ?? []), id])]);
  };
  for (const f of [
    "docs/emr/clinical-fact-concepts.v1.json",
    ...["1", "2", "3", "5", "6"].map((v) => `data/emr/clinical-fact-concepts.v1.${v}.json`),
  ])
    for (const c of read(f).concepts as Json[])
      for (const k of (c.codes ?? []) as Json[]) if (k.system === "LOINC") add(k.code, c.id);
  for (const c of read("docs/lab/catalogue-research/lab-catalogue-research.v1.json")
    .concepts as Json[])
    if (c.loinc?.status === "verified") add(c.loinc.code, c.id);
  for (const c of read("docs/lab/test-menu-v2/lab-catalogue-v2.json").concepts as Json[])
    if (c.loinc.status === "verified") add(c.loinc.code, c.id);
  return m;
}

/** A hub unit's A.3 code (or its label, from a capture) → the catalogue section. */
export function sectionOfUnit(codeOrLabel: string | null): SectionKey | null {
  const a3 = LAB_SECTIONS.find((s) => s.code === codeOrLabel || s.label === codeOrLabel)?.code;
  const key = a3 === "serology_immunology" ? "immunology_serology" : (a3 ?? codeOrLabel);
  return (SECTIONS.find((s) => s.key === key || s.display === codeOrLabel)?.key ??
    null) as SectionKey | null;
}

export function reportMarkdown(
  byHospital: { name: string; legacy: number; plan: MigrationPlan }[],
  mode: string,
) {
  const out = [
    "# TM-9 migration report: per-LOINC settings to tests",
    "",
    `${mode}. Generated by \`scripts/lab/migrate-offerings.ts\` (rule: \`planOfferingMigration\`, TM-9, TM-D10).`,
    "A LOINC row maps to every catalogue test whose results carry that code. Coverage is how many of the test's",
    "results had a set row. Conflicts take the most common value and are listed here; nothing is resolved silently.",
    "",
  ];
  for (const h of byHospital) {
    const p = h.plan;
    out.push(
      `## ${h.name}`,
      "",
      `${h.legacy} LOINC rows → ${p.rows.length} tests · ${p.conflicts.length} conflicts · ${p.unmapped.length} unmapped · ${p.skipped.length} already set as tests (kept)`,
      "",
    );
    if (p.rows.length) {
      out.push(
        "| Test | Where | Hours | Stated turnaround | Section override | Coverage | From |",
        "|---|---|---|---|---|---|---|",
      );
      for (const r of p.rows)
        out.push(
          `| \`${r.code}\` | ${r.where} | ${r.hours ?? "—"}${r.hoursNote ? ` (${r.hoursNote})` : ""} | ${r.statedTat ?? "—"} | ${r.sectionOverride ?? "—"} | ${r.coverage} | ${r.from.join(", ")} |`,
        );
      out.push("");
    }
    if (p.conflicts.length) {
      out.push("**Conflicts**", "");
      for (const c of p.conflicts)
        out.push(
          `- \`${c.code}\` ${c.field}: ${Object.entries(c.values)
            .map(([k, v]) => `${k} = ${v}`)
            .join("; ")}`,
        );
      out.push("");
    }
    if (p.unmapped.length) out.push(`**Unmapped LOINC rows:** ${p.unmapped.join(", ")}`, "");
    if (p.skipped.length) out.push(`**Already set as tests (kept):** ${p.skipped.join(", ")}`, "");
  }
  return out.join("\n");
}

const toLegacy = (r: Json, section: SectionKey | null): LegacyRow => ({
  code: r.code,
  provision: r.provision,
  hours: r.hours ?? null,
  hoursNote: r.hoursNote ?? r.hours_note ?? null,
  statedTat: r.statedTat ?? r.stated_tat ?? null,
  referredTo: r.referredTo ?? r.referred_to ?? null,
  section,
});

/** The database run: every hospital with a LOINC-keyed lab row. Exported for the PGlite lane. */
export async function migrateOfferings(db: EmrDb, apply: boolean, actor: string | undefined) {
  const loincTo = loincIndex();
  const tests = await db
    .select({
      code: testCatalogue.code,
      section: testCatalogue.section,
      components: testCatalogue.components,
    })
    .from(testCatalogue)
    .where(
      and(
        isNull(testCatalogue.hospitalId),
        eq(testCatalogue.kind, "lab"),
        isNotNull(testCatalogue.section),
      ),
    );
  const codes = new Set(tests.map((t) => t.code));
  const rows = await db
    .select({
      hospitalId: diagnosticOfferings.hospitalId,
      code: diagnosticOfferings.code,
      provision: diagnosticOfferings.provision,
      hours: diagnosticOfferings.hours,
      hoursNote: diagnosticOfferings.hoursNote,
      statedTat: diagnosticOfferings.statedTat,
      referredTo: diagnosticOfferings.referredTo,
      unit: hospitalDepartments.catalogueCode,
      name: hospitals.name,
    })
    .from(diagnosticOfferings)
    .innerJoin(hospitals, eq(hospitals.id, diagnosticOfferings.hospitalId))
    .leftJoin(hospitalDepartments, eq(hospitalDepartments.id, diagnosticOfferings.sectionId))
    .where(eq(diagnosticOfferings.kind, "lab"));
  const result: { hospitalId: string; name: string; legacy: number; plan: MigrationPlan }[] = [];
  for (const hospitalId of [...new Set(rows.map((r) => r.hospitalId))]) {
    const mine = rows.filter((r) => r.hospitalId === hospitalId);
    const legacy = mine.filter((r) => !codes.has(r.code));
    if (!legacy.length) continue;
    result.push({
      hospitalId,
      name: mine[0]!.name,
      legacy: legacy.length,
      plan: planOfferingMigration({
        legacy: legacy.map((r) => toLegacy(r, sectionOfUnit(r.unit))),
        tests: tests.map((t) => ({
          code: t.code,
          section: t.section as SectionKey,
          components: t.components,
        })),
        loincTo,
        existing: new Set(mine.filter((r) => codes.has(r.code)).map((r) => r.code)),
      }),
    });
  }
  if (apply) {
    const now = new Date();
    await db.transaction(async (tx) => {
      await asActor(tx, actor);
      for (const h of result)
        for (const r of h.plan.rows)
          await tx
            .insert(diagnosticOfferings)
            .values({
              hospitalId: h.hospitalId,
              kind: "lab",
              code: r.code,
              provision: r.where,
              sectionOverride: r.sectionOverride,
              hours: r.hours,
              hoursNote: r.hoursNote,
              statedTat: r.statedTat,
              referredTo: r.referredTo,
              confirmedAt: now,
              updatedBy: actor ?? null,
            })
            .onConflictDoNothing();
    });
  }
  return result;
}

/** Offline: a capture (`{offs: [...]}` rows with `hospital` and `section_name`) against the catalogue file. */
export function planFromCapture(file: string) {
  const offs = (JSON.parse(readFileSync(file, "utf8")).offs ?? []) as Json[];
  const tests = (read("docs/lab/test-menu-v2/lab-catalogue-v2.json").tests as Json[]).map((t) => ({
    code: t.id as string,
    section: t.section as SectionKey,
    components: t.components as string[],
  }));
  const codes = new Set(tests.map((t) => t.code));
  return [...new Set(offs.map((o) => o.hospital as string))].map((name) => {
    const mine = offs.filter((o) => o.hospital === name && o.kind === "lab");
    const legacy = mine.filter((o) => !codes.has(o.code));
    return {
      name,
      legacy: legacy.length,
      plan: planOfferingMigration({
        legacy: legacy.map((o) => toLegacy(o, sectionOfUnit(o.section_name ?? null))),
        tests,
        loincTo: loincIndex(),
        existing: new Set(mine.filter((o) => codes.has(o.code)).map((o) => o.code)),
      }),
    };
  });
}

if (process.argv[1]?.endsWith("migrate-offerings.ts")) {
  const i = process.argv.indexOf("--rows");
  if (i > 0) {
    const plans = planFromCapture(process.argv[i + 1]!);
    writeFileSync(
      join(root, REPORT),
      reportMarkdown(plans, "Dry run from a capture (no database)") + "\n",
    );
    for (const p of plans) console.log(`${p.name}: ${p.legacy} rows → ${p.plan.rows.length} tests`);
  } else
    void runCli(
      "TM-9: per-LOINC lab offerings to per-test offerings. Dry run by default; --apply --actor <uuid> writes.",
      async ({ db, apply, actor }) => {
        const r = await migrateOfferings(db, apply, actor);
        writeFileSync(join(root, REPORT), reportMarkdown(r, apply ? "Applied" : "Dry run") + "\n");
        for (const h of r) console.log(`${h.name}: ${h.legacy} rows → ${h.plan.rows.length} tests`);
        if (!apply) console.log("Dry run: nothing written. Report at " + REPORT);
      },
    );
}
