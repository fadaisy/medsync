/**
 * Shadow report for the diabetes pack (Phase 6): runs the pack over the synthetic patients
 * (tests/ncd/fixtures/diabetes-pack-vignettes.json), each at a referral site and at a district
 * site, and counts how often each rule, management step and therapy flag fires. Synthetic only:
 * no record is read. Writes docs/ncd/diabetes/phase-6/shadow-report.md.
 *
 *   npx tsx scripts/ncd-pack-shadow-report.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import type { PackInput, PackValues } from "@/lib/ncd/pack/types";

import { diabetesPack, runDiabetesPack } from "@/lib/ncd/pack";

type Vignette = {
  id: string;
  established: boolean;
  ageBand: PackInput["ageBand"];
  values: PackValues;
};
const fixture = JSON.parse(
  readFileSync("tests/ncd/fixtures/diabetes-pack-vignettes.json", "utf8"),
) as { sites: { district: string[] }; vignettes: Vignette[] };
const pack = diabetesPack();
const SITES = { referral: "referral", district: "district" } as const;

const items = [
  ...pack.rules.map((r) => ({ id: r.id, kind: "rule", x: r.x })),
  ...pack.management.map((s) => ({ id: s.id, kind: "step", x: s.x })),
  ...pack.therapyFlags.map((f) => ({ id: f.id, kind: "therapy flag", x: f.x })),
];
const n = fixture.vignettes.length;
const fires: Record<string, Record<string, number>> = { referral: {}, district: {} };
const dark: Record<string, number> = {};
const interrupts: Record<string, number> = { referral: 0, district: 0 };
for (const [name, site] of Object.entries(SITES))
  for (const v of fixture.vignettes) {
    const r = runDiabetesPack({
      values: v.values,
      site,
      established: v.established,
      ageBand: v.ageBand,
    });
    for (const id of Object.keys(r.fired)) fires[name]![id] = (fires[name]![id] ?? 0) + 1;
    if (name === "referral") for (const id of Object.keys(r.dark)) dark[id] = (dark[id] ?? 0) + 1;
    if (r.interrupt) interrupts[name]!++;
  }

const pct = (k: number) => `${((100 * k) / n).toFixed(1)}%`;
const on = items.filter((i) => i.x.enabled !== false);
const never = on.filter((i) => !fires.referral![i.id] && !fires.district![i.id]);
const noisy = on.filter(
  (i) => Math.max(fires.referral![i.id] ?? 0, fires.district![i.id] ?? 0) / n > 0.2,
);
const row = (i: (typeof items)[number]) =>
  `| \`${i.id}\` | ${i.kind} | ${i.x.lane ?? i.x.kind ?? ""} | ${fires.referral![i.id] ?? 0} (${pct(fires.referral![i.id] ?? 0)}) | ${fires.district![i.id] ?? 0} (${pct(fires.district![i.id] ?? 0)}) |`;
const HEAD = "| Item | Kind | Lane | Referral | District |\n|---|---|---|---|---|";

const md = `# Shadow report: the diabetes pack over the synthetic patients

Pack ${pack.pack.id} ${pack.pack.version}. ${n} synthetic patients (the vignettes), each run at a referral site and at a district site (${fixture.sites.district.length} capabilities). No patient record was read. Generated by \`npx tsx scripts/ncd-pack-shadow-report.ts\`.

The vignettes were written to exercise the pack, so these are coverage rates, not the rates a clinic would see. A real shadow rate needs the flag on in a clinic (\`NCD_DM_PACK_SHADOW=1\`), which logs ids and counts only.

| | Referral | District |
|---|---|---|
| Items switched on (rules, steps, therapy flags) | ${on.length} | ${on.length} |
| Patients with an interrupt | ${interrupts.referral} (${pct(interrupts.referral!)}) | ${interrupts.district} (${pct(interrupts.district!)}) |
| Items fired at least once | ${on.filter((i) => fires.referral![i.id]).length} | ${on.filter((i) => fires.district![i.id]).length} |

Dark items (off until a decision switches them on): ${items.length - on.length}; reported, never shown.

## Never fired on any synthetic patient (${never.length})

${never.length ? `${HEAD}\n${never.map(row).join("\n")}` : "None."}

Every one of them can fire. A synthesiser built a patient who meets each item's trigger and ran it: 49 fired on that patient, and the other two (\`DM-ACT-REFER-TARGET-01\`, \`DM-ACT-RX-03\`) need metformin and a sulfonylurea in the same list, which fires both at both sites when written by hand. They are uncovered, not dead. Go-live item: a vignette for each, so parity guards them (the mutation test covers the acute lane, red flags and blocking caveats only).

## Fired on more than 20% of patients (${noisy.length})

${noisy.length ? `${HEAD}\n${noisy.map(row).join("\n")}` : "None."}

Both are routine counselling steps that run for everyone with established diabetes, once per visit, with no urgency. A rate above 20% is expected for them and is not noise.

## Every item

${HEAD}
${on.map(row).join("\n")}
`;
writeFileSync("docs/ncd/diabetes/phase-6/shadow-report.md", md);
console.log({
  n,
  on: on.length,
  never: never.map((i) => i.id),
  noisy: noisy.map((i) => i.id),
  interrupts,
});
